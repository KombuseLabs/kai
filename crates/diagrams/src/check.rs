//! The checks: every Mermaid block of the repository's Markdown says how it
//! stays true, and does.
//!
//! - **Every block has a header** ([`crate::header`]). A block without one
//!   is a finding at its fence.
//! - **`checked against`**: a class diagram's code classes are compared
//!   with the crates' types ([`crate::model::compare`] and
//!   [`crate::model::relation_problems`]); a sequence diagram's messages to
//!   a participant that is a code path (`store::Store`, `engine::qualify`)
//!   must name a method of that type or a function of that module.
//! - **`shows every variant of`**: every variant of the enum appears as a
//!   word in some state of the state diagram, but those named after `but`.
//! - **`drawn from`**: each item's stamp is the one its code has now.
//! - **`generated by`**: the program named exists; it checks its block
//!   itself.
//!
//! ```
//! use diagrams::check::Checker;
//!
//! let checker = Checker::new(std::path::Path::new("."));
//! let findings = checker.check_markdown("doc.md", "```mermaid\nflowchart TD\n  A --> B\n```\n");
//! assert_eq!(findings.len(), 1);
//! assert!(findings[0].message.contains("says not how it stays true"));
//! ```

use std::cell::RefCell;
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::rc::Rc;

use crate::Finding;
use crate::header::{FORMS, Header, Stamped};
use crate::markdown::{Block, mermaid_blocks};
use crate::mermaid::{self, Kind};
use crate::model::{self, Kind as ItemKind, TypeDef};
use crate::rust::{CrateModel, Resolved, module_text};

/// Directories the walk over the repository leaves out, relative to the
/// root: the build, the maintainers' board, and this crate's fixtures,
/// which break the rules on purpose.
pub const SKIPPED: &[&str] = &["target", "board", "crates/diagrams/tests/fixtures"];

/// Runs the checks; keeps each crate it read for the next block.
pub struct Checker {
    root: PathBuf,
    crates: RefCell<BTreeMap<String, Result<Rc<CrateModel>, String>>>,
}

impl Checker {
    /// A checker for the repository at `root`.
    pub fn new(root: &Path) -> Checker {
        Checker {
            root: root.to_owned(),
            crates: RefCell::new(BTreeMap::new()),
        }
    }

    /// Every Markdown file under the root, relative to it, sorted, but
    /// those under [`SKIPPED`] and dot directories.
    pub fn markdown_files(&self) -> Vec<PathBuf> {
        let mut files = Vec::new();
        walk(&self.root, Path::new(""), &mut files);
        files.sort();
        files
    }

    /// Checks one file, `path` relative to the root.
    pub fn check_file(&self, path: &Path) -> Vec<Finding> {
        let label = path.to_string_lossy().replace('\\', "/");
        match std::fs::read_to_string(self.root.join(path)) {
            Ok(text) => self.check_markdown(&label, &text),
            Err(err) => vec![Finding {
                file: label,
                line: 1,
                message: format!("cannot read it: {err}"),
            }],
        }
    }

    /// Checks the Mermaid blocks of `text`, a Markdown file named `label`.
    pub fn check_markdown(&self, label: &str, text: &str) -> Vec<Finding> {
        let mut findings = Vec::new();
        for block in mermaid_blocks(text) {
            self.check_block(label, &block, &mut findings);
        }
        findings
    }

    fn check_block(&self, label: &str, block: &Block, findings: &mut Vec<Finding>) {
        let mut at = |line: usize, message: String| {
            findings.push(Finding {
                file: label.to_owned(),
                line: block.file_line(line),
                message,
            });
        };
        if block.unclosed {
            findings.push(Finding {
                file: label.to_owned(),
                line: block.fence_line,
                message: "the Mermaid block has no closing fence".to_owned(),
            });
            return;
        }
        let header = match Header::parse(&block.text) {
            Ok(header) => header,
            Err(err) => {
                at(err.line, err.message);
                return;
            }
        };
        if header.is_empty() {
            findings.push(Finding {
                file: label.to_owned(),
                line: block.fence_line,
                message: format!(
                    "the diagram says not how it stays true to the code; its first lines are one or more of {FORMS}"
                ),
            });
            return;
        }
        let (kind, _) = Kind::of(&block.text);
        let mut local = Vec::new();
        if let Some(generated) = &header.generated
            && !self.root.join(&generated.value).is_file()
        {
            local.push((
                generated.line,
                format!(
                    "`{}`, which generates this block, does not exist",
                    generated.value
                ),
            ));
        }
        if let Some(checked) = &header.checked {
            match kind {
                Kind::Class => self.check_class(&block.text, &checked.value.crates, checked.line, &mut local),
                Kind::Sequence => self.check_sequence(&block.text, &checked.value.crates, checked.line, &mut local),
                ref other => local.push((
                    checked.line,
                    format!("`checked against` reads class and sequence diagrams; a {other} is drawn (`drawn from …`)"),
                )),
            }
        }
        if let Some(shows) = &header.shows {
            if kind == Kind::State {
                self.check_state(
                    &block.text,
                    &shows.value.path,
                    &shows.value.except,
                    shows.line,
                    &mut local,
                );
            } else {
                local.push((
                    shows.line,
                    format!("`shows every variant of` reads state diagrams, not a {kind}"),
                ));
            }
        }
        for stamped in &header.drawn {
            self.check_stamp(stamped, &mut local);
        }
        for (line, message) in local {
            at(line, message);
        }
    }

    /// The crate in `dir`, read once.
    fn crate_model(&self, dir: &str) -> Result<Rc<CrateModel>, String> {
        let mut crates = self.crates.borrow_mut();
        crates
            .entry(dir.to_owned())
            .or_insert_with(|| CrateModel::load(&self.root, dir).map(Rc::new))
            .clone()
    }

    /// The crate of that name: `crates/<name>`.
    fn crate_named(&self, name: &str) -> Result<Rc<CrateModel>, String> {
        self.crate_model(&format!("crates/{name}"))
    }

    fn check_class(
        &self,
        text: &str,
        dirs: &[String],
        header_line: usize,
        out: &mut Vec<(usize, String)>,
    ) {
        let diagram = match mermaid::class::parse(text) {
            Ok(diagram) => diagram,
            Err(err) => return out.push((err.line, err.message)),
        };
        let (classes, problems) = model::diagram_classes(&diagram);
        out.extend(problems.into_iter().map(|p| (p.line, p.message)));
        let mut models = Vec::new();
        for dir in dirs {
            match self.crate_model(dir) {
                Ok(model) => models.push(model),
                Err(err) => out.push((header_line, err)),
            }
        }
        if models.len() != dirs.len() {
            return;
        }
        let in_crates = dirs.join(", ");
        let mut found: BTreeMap<String, TypeDef> = BTreeMap::new();
        for class in classes.iter().filter(|class| class.code) {
            let name = &class.def.name;
            let def = if class.def.kind == ItemKind::Function {
                let functions: Vec<(&CrateModel, &crate::rust::CodeFn)> = models
                    .iter()
                    .flat_map(|model| {
                        model
                            .functions_named(name)
                            .into_iter()
                            .map(move |f| (&**model, f))
                    })
                    .collect();
                match functions.as_slice() {
                    [(model, function)] => model.function_def(function),
                    [] => {
                        out.push((class.def.line, format!("class `{name}` is a <<function>>; no function `{name}` is in {in_crates}")));
                        continue;
                    }
                    several => {
                        let places: Vec<String> = several
                            .iter()
                            .map(|(m, f)| module_text(&m.name, &f.module))
                            .collect();
                        out.push((
                            class.def.line,
                            format!(
                                "more than one function is named `{name}`: in {}",
                                places.join(", ")
                            ),
                        ));
                        continue;
                    }
                }
            } else {
                let types: Vec<(&CrateModel, &crate::rust::CodeType)> = models
                    .iter()
                    .flat_map(|model| {
                        model
                            .types_named(name)
                            .into_iter()
                            .map(move |t| (&**model, t))
                    })
                    .collect();
                match types.as_slice() {
                    [(_, ty)] => ty.def.clone(),
                    [] => {
                        out.push((
                            class.def.line,
                            format!("class `{name}` names no struct, enum or trait in {in_crates}"),
                        ));
                        continue;
                    }
                    several => {
                        let places: Vec<String> = several
                            .iter()
                            .map(|(m, t)| module_text(&m.name, &t.module))
                            .collect();
                        out.push((class.def.line, format!(
                            "more than one type is named `{name}`: in {}; check against fewer crates",
                            places.join(", ")
                        )));
                        continue;
                    }
                }
            };
            for problem in model::compare(class, &def) {
                out.push((problem.line, problem.message));
            }
            found.insert(name.clone(), def);
        }
        let lookup = |name: &str| found.get(name);
        for problem in model::relation_problems(&diagram, &classes, &lookup) {
            out.push((problem.line, problem.message));
        }
    }

    fn check_sequence(
        &self,
        text: &str,
        dirs: &[String],
        header_line: usize,
        out: &mut Vec<(usize, String)>,
    ) {
        let diagram = match mermaid::sequence::parse(text) {
            Ok(diagram) => diagram,
            Err(err) => return out.push((err.line, err.message)),
        };
        // The participants that are code: alias → what they are.
        let mut code: BTreeMap<String, (Rc<CrateModel>, Resolved2)> = BTreeMap::new();
        for participant in &diagram.participants {
            let Some(segments) = code_path(&participant.description) else {
                continue;
            };
            let crate_name = segments[0];
            let Some(dir) = dirs
                .iter()
                .find(|dir| Path::new(dir).file_name().is_some_and(|n| n == crate_name))
            else {
                out.push((participant.line, format!(
                    "participant `{}` is `{}`, of the crate `{crate_name}`, which `checked against` does not name",
                    participant.alias, participant.description
                )));
                continue;
            };
            let model = match self.crate_model(dir) {
                Ok(model) => model,
                Err(err) => {
                    out.push((header_line, err));
                    continue;
                }
            };
            let resolved = match model.resolve(&segments[1..]) {
                Resolved::Module(path) => Resolved2::Module(path),
                Resolved::Type(ty) => Resolved2::Type(ty.def.clone()),
                Resolved::Ambiguous(why) => {
                    out.push((
                        participant.line,
                        format!("participant `{}`: {why}", participant.alias),
                    ));
                    continue;
                }
                _ => {
                    out.push((
                        participant.line,
                        format!(
                            "participant `{}` is `{}`, which names no module or type in {dir}",
                            participant.alias, participant.description
                        ),
                    ));
                    continue;
                }
            };
            code.insert(participant.alias.clone(), (model, resolved));
        }
        for message in &diagram.messages {
            if message.reply || message.from == message.to {
                continue;
            }
            let Some((model, target)) = code.get(&message.to) else {
                continue;
            };
            let name: String = message
                .label
                .chars()
                .take_while(|c| c.is_alphanumeric() || *c == '_')
                .collect();
            let description = &diagram.participant(&message.to).expect("named").description;
            if name.is_empty() {
                out.push((message.line, format!(
                    "a message to `{description}` starts with the name of what it calls, as in `cursor(board)`"
                )));
                continue;
            }
            let exists = match target {
                Resolved2::Type(def) => def.methods.iter().any(|method| method.name == name),
                Resolved2::Module(path) => model
                    .functions
                    .iter()
                    .any(|function| &function.module == path && function.function.name == name),
            };
            if !exists {
                let what = match target {
                    Resolved2::Type(_) => format!("`{description}` has no method `{name}`"),
                    Resolved2::Module(_) => {
                        format!("the module `{description}` has no function `{name}`")
                    }
                };
                out.push((
                    message.line,
                    format!("the message `{}` calls `{name}`; {what}", message.label),
                ));
            }
        }
    }

    fn check_state(
        &self,
        text: &str,
        path: &str,
        except: &[String],
        header_line: usize,
        out: &mut Vec<(usize, String)>,
    ) {
        let diagram = match mermaid::state::parse(text) {
            Ok(diagram) => diagram,
            Err(err) => return out.push((err.line, err.message)),
        };
        let segments: Vec<&str> = path.split("::").collect();
        let model = match self.crate_named(segments[0]) {
            Ok(model) => model,
            Err(err) => return out.push((header_line, err)),
        };
        let def = match model.resolve(&segments[1..]) {
            Resolved::Type(ty) if ty.def.kind == ItemKind::Enum => ty.def.clone(),
            Resolved::Ambiguous(why) => return out.push((header_line, why)),
            _ => {
                return out.push((
                    header_line,
                    format!("`{path}` names no enum in crates/{}", segments[0]),
                ));
            }
        };
        let words: std::collections::BTreeSet<&str> = diagram
            .states
            .iter()
            .flat_map(|state| {
                std::iter::once(state.name.as_str())
                    .chain(state.descriptions.iter().map(String::as_str))
            })
            .flat_map(|text| text.split(|c: char| !(c.is_alphanumeric() || c == '_')))
            .filter(|word| !word.is_empty())
            .collect();
        for name in except {
            if !def.variants.iter().any(|variant| &variant.name == name) {
                out.push((
                    header_line,
                    format!("`{path}` has no variant `{name}` to leave out"),
                ));
            }
        }
        for variant in &def.variants {
            if except.contains(&variant.name) || words.contains(variant.name.as_str()) {
                continue;
            }
            let at = def
                .location
                .as_ref()
                .map(|location| format!(" ({}:{})", location.file, variant.line))
                .unwrap_or_default();
            out.push((header_line, format!(
                "no state shows `{path}::{}`{at}; name it in a state, or after `but` in the header",
                variant.name
            )));
        }
    }

    fn check_stamp(&self, stamped: &Stamped, out: &mut Vec<(usize, String)>) {
        let segments: Vec<&str> = stamped.path.split("::").collect();
        let model = match self.crate_named(segments[0]) {
            Ok(model) => model,
            Err(err) => return out.push((stamped.line, err)),
        };
        let actual =
            match model.resolve(&segments[1..]) {
                Resolved::Type(ty) => ty.def.stamp.clone(),
                Resolved::Function(function) => function.function.stamp.clone(),
                Resolved::Method(_, method) => method.stamp.clone(),
                Resolved::Module(_) => {
                    return out.push((stamped.line, format!(
                    "`{}` is a module; a diagram is drawn from functions, types and methods",
                    stamped.path
                )));
                }
                Resolved::Ambiguous(why) => {
                    return out.push((stamped.line, format!("`{}`: {why}", stamped.path)));
                }
                Resolved::Nothing => {
                    return out.push((
                        stamped.line,
                        format!(
                            "`{}`, which the diagram is drawn from, is not in crates/{}",
                            stamped.path, segments[0]
                        ),
                    ));
                }
            };
        let actual = actual.unwrap_or_default();
        match &stamped.stamp {
            None => out.push((stamped.line, format!(
                "`{}` has no stamp; look whether the diagram holds, then write `{}#{actual}`",
                stamped.path, stamped.path
            ))),
            Some(stamp) if *stamp != actual => out.push((stamped.line, format!(
                "the diagram is drawn from `{}`, which changed. Look whether the diagram still holds and change it if not; then set the stamp to #{actual}",
                stamped.path
            ))),
            Some(_) => {}
        }
    }
}

/// What a code participant is.
enum Resolved2 {
    Module(Vec<String>),
    Type(TypeDef),
}

/// `crate::a::B` as its segments, if `text` is such a path.
fn code_path(text: &str) -> Option<Vec<&str>> {
    let segments: Vec<&str> = text.split("::").collect();
    let first = segments.first()?;
    let crate_like = first
        .chars()
        .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
        && !first.is_empty();
    (segments.len() >= 2 && crate_like && segments.iter().all(|s| mermaid::is_ident(s)))
        .then_some(segments)
}

fn walk(root: &Path, relative: &Path, files: &mut Vec<PathBuf>) {
    let Ok(entries) = std::fs::read_dir(root.join(relative)) else {
        return;
    };
    for entry in entries.flatten() {
        let name = entry.file_name();
        let name = name.to_string_lossy();
        let path = relative.join(&*name);
        let Ok(kind) = entry.file_type() else {
            continue;
        };
        if kind.is_dir() {
            let skipped = name.starts_with('.')
                || SKIPPED
                    .iter()
                    .any(|skip| path.to_string_lossy().replace('\\', "/") == *skip);
            if !skipped {
                walk(root, &path, files);
            }
        } else if kind.is_file() && name.ends_with(".md") {
            files.push(path);
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn code_paths_are_crate_paths() {
        assert_eq!(code_path("store::Store"), Some(vec!["store", "Store"]));
        assert_eq!(
            code_path("engine::qualify"),
            Some(vec!["engine", "qualify"])
        );
        assert_eq!(code_path("kai (cli)"), None);
        assert_eq!(code_path("Store"), None);
        assert_eq!(code_path("GitHub::Api"), None);
    }

    #[test]
    fn a_header_line_that_is_wrong_is_found_at_its_line() {
        let checker = Checker::new(Path::new("."));
        let findings = checker.check_markdown(
            "x.md",
            "text\n\n```mermaid\n%% checked against\nclassDiagram\n```\n",
        );
        assert_eq!(findings[0].line, 4);
    }
}
