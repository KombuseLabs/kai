//! The crate graph: a box for each crate under `crates/`, an arrow for
//! each `[dependencies]` entry that names another of them, and the rules
//! about it that `AGENTS.md` states.
//!
//! `crates/diagrams/tests/crates.rs` writes it into `docs/crates.md` with
//! `UPDATE_DIAGRAMS=1`, and otherwise fails when the block there differs.
//!
//! ```
//! use std::collections::{BTreeMap, BTreeSet};
//! use diagrams::graph::{Workspace, flowchart, rule_violations};
//!
//! let workspace = Workspace {
//!     crates: BTreeMap::from([
//!         ("cli".to_owned(), BTreeSet::from(["types".to_owned()])),
//!         ("types".to_owned(), BTreeSet::new()),
//!     ]),
//! };
//! assert!(flowchart(&workspace).contains("    cli --> types\n"));
//! assert!(rule_violations(&workspace).is_empty());
//! ```

use std::collections::{BTreeMap, BTreeSet};
use std::path::Path;

use crate::header::Header;
use crate::markdown::mermaid_blocks;

/// The program that writes the graph, as its header names it.
pub const GENERATOR: &str = "crates/diagrams/tests/crates.rs";

/// The page the graph is on.
pub const PAGE: &str = "docs/crates.md";

/// Crates that depend on no crate of kai's, and why.
pub const LEAVES: &[(&str, &str)] = &[
    (
        "types",
        "the domain types are data only and depend on nothing of kai's (AGENTS.md)",
    ),
    (
        "helpers",
        "helpers is infrastructure, beneath every crate that does what kai does",
    ),
    ("guest", "kai's init is built alone, static, for the guest"),
];

/// Crates nothing may depend on, and why.
pub const NOT_DEPENDED_ON: &[(&str, &str)] = &[(
    "diagrams",
    "the diagram checks are a maintainer's tool, not part of the program",
)];

/// The workspace's crates and which of each other they depend on.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Workspace {
    /// Each crate's name and the workspace crates in its `[dependencies]`.
    pub crates: BTreeMap<String, BTreeSet<String>>,
}

/// Reads `crates/*/Cargo.toml` under `root`.
pub fn read(root: &Path) -> Result<Workspace, String> {
    let dir = root.join("crates");
    let entries = std::fs::read_dir(&dir).map_err(|err| format!("cannot read crates/: {err}"))?;
    let mut manifests = BTreeMap::new();
    for entry in entries.flatten() {
        let manifest = entry.path().join("Cargo.toml");
        if !manifest.is_file() {
            continue;
        }
        let text = std::fs::read_to_string(&manifest)
            .map_err(|err| format!("cannot read {}: {err}", manifest.display()))?;
        let table: toml::Table = text
            .parse()
            .map_err(|err| format!("cannot parse {}: {err}", manifest.display()))?;
        let name = table
            .get("package")
            .and_then(|package| package.get("name"))
            .and_then(|name| name.as_str())
            .ok_or_else(|| format!("{} names no package", manifest.display()))?
            .to_owned();
        let mut dependencies = BTreeSet::new();
        if let Some(table) = table.get("dependencies").and_then(|d| d.as_table()) {
            for (key, value) in table {
                let package = value
                    .get("package")
                    .and_then(|package| package.as_str())
                    .unwrap_or(key);
                dependencies.insert(package.to_owned());
            }
        }
        manifests.insert(name, dependencies);
    }
    let names: BTreeSet<String> = manifests.keys().cloned().collect();
    let crates = manifests
        .into_iter()
        .map(|(name, dependencies)| {
            let ours = dependencies.intersection(&names).cloned().collect();
            (name, ours)
        })
        .collect();
    Ok(Workspace { crates })
}

/// The block's text: the header, every crate, then every arrow.
pub fn flowchart(workspace: &Workspace) -> String {
    let mut text = format!("%% generated by {GENERATOR}; do not edit\nflowchart TD\n");
    for name in workspace.crates.keys() {
        text.push_str(&format!("    {name}\n"));
    }
    for (name, dependencies) in &workspace.crates {
        for dependency in dependencies {
            text.push_str(&format!("    {name} --> {dependency}\n"));
        }
    }
    text
}

/// The rules the graph breaks, one sentence each.
pub fn rule_violations(workspace: &Workspace) -> Vec<String> {
    let mut violations = Vec::new();
    for (leaf, why) in LEAVES {
        if let Some(dependencies) = workspace.crates.get(*leaf)
            && !dependencies.is_empty()
        {
            let list: Vec<&str> = dependencies.iter().map(String::as_str).collect();
            violations.push(format!("`{leaf}` depends on {}; {why}", list.join(", ")));
        }
    }
    for (name, why) in NOT_DEPENDED_ON {
        for (user, dependencies) in &workspace.crates {
            if dependencies.contains(*name) {
                violations.push(format!("`{user}` depends on `{name}`; {why}"));
            }
        }
    }
    violations
}

/// `markdown` with the text of its block generated by [`GENERATOR`]
/// replaced by `text`.
pub fn replace_block(markdown: &str, text: &str) -> Result<String, String> {
    let block = generated_block(markdown)?;
    let lines: Vec<&str> = markdown.lines().collect();
    let mut out = String::new();
    for line in &lines[..block.fence_line] {
        out.push_str(line);
        out.push('\n');
    }
    out.push_str(text);
    let closing = block.first_line - 1 + block.text.lines().count();
    for line in &lines[closing..] {
        out.push_str(line);
        out.push('\n');
    }
    Ok(out)
}

/// The text of the block generated by [`GENERATOR`] in `markdown`.
pub fn generated_text(markdown: &str) -> Result<String, String> {
    generated_block(markdown).map(|block| block.text)
}

fn generated_block(markdown: &str) -> Result<crate::markdown::Block, String> {
    let mut found: Vec<crate::markdown::Block> = mermaid_blocks(markdown)
        .into_iter()
        .filter(|block| {
            Header::parse(&block.text)
                .ok()
                .and_then(|header| header.generated)
                .is_some_and(|generated| generated.value == GENERATOR)
        })
        .collect();
    match found.len() {
        1 => Ok(found.remove(0)),
        0 => Err(format!(
            "no Mermaid block says `%% generated by {GENERATOR}; do not edit`"
        )),
        _ => Err(format!(
            "more than one block says it is generated by {GENERATOR}"
        )),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn workspace(pairs: &[(&str, &[&str])]) -> Workspace {
        Workspace {
            crates: pairs
                .iter()
                .map(|(name, deps)| {
                    (
                        (*name).to_owned(),
                        deps.iter().map(|d| (*d).to_owned()).collect(),
                    )
                })
                .collect(),
        }
    }

    #[test]
    fn leaves_and_the_tool_are_rules() {
        let broken = workspace(&[
            ("types", &["helpers"]),
            ("helpers", &[]),
            ("vm", &["diagrams"]),
            ("diagrams", &[]),
        ]);
        let violations = rule_violations(&broken);
        assert_eq!(violations.len(), 2, "{violations:?}");
        assert!(violations[0].starts_with("`types` depends on helpers"));
        assert!(violations[1].starts_with("`vm` depends on `diagrams`"));
    }

    #[test]
    fn the_block_is_replaced_in_place() {
        let page = format!(
            "# Crates\n\n```mermaid\n%% generated by {GENERATOR}; do not edit\nflowchart TD\n    old\n```\n\nAfter.\n"
        );
        let text = flowchart(&workspace(&[("a", &["b"]), ("b", &[])]));
        let new = replace_block(&page, &text).unwrap();
        assert_eq!(generated_text(&new).unwrap(), text);
        assert!(new.ends_with("```\n\nAfter.\n"));
        assert!(new.starts_with("# Crates\n\n```mermaid\n%% generated"));
    }
}
